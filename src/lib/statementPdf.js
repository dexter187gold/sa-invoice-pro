import { jsPDF } from 'jspdf'
import { formatMoney } from './money'
import { openWhatsApp, openEmail, buildClientStatement } from './share'
import { buildClientLedger } from './payments'

/** Build open-invoice rows for a client */
export function openInvoicesForClient(client, invoices) {
  return (invoices || [])
    .filter((i) => String(i.clientId) === String(client?.id) && ['unpaid', 'partial', 'overdue'].includes(i.status || 'unpaid'))
    .sort((a, b) => String(a.dueDate || a.date || '').localeCompare(String(b.dueDate || b.date || '')))
}

export function statementTotals(rows) {
  return rows.reduce((s, i) => s + (Number(i.amountDue ?? i.total) || 0), 0)
}

/** Generate full account statement PDF (invoices + payments) */
export function buildStatementPdfBlob(client, invoices, company, payments = []) {
  const { lines, outstanding } = buildClientLedger(client, invoices, payments)
  const doc = new jsPDF({ unit: 'mm', format: 'a4' })
  const co = company?.name || 'SA Invoice Pro'
  let y = 18

  doc.setFontSize(16)
  doc.setTextColor(0, 122, 77)
  doc.text(co, 14, y)
  y += 8
  doc.setFontSize(12)
  doc.setTextColor(30)
  doc.text('Account statement', 14, y)
  y += 7
  doc.setFontSize(10)
  doc.setTextColor(80)
  doc.text(`Date: ${new Date().toISOString().slice(0, 10)}`, 14, y)
  y += 10

  doc.setTextColor(20)
  doc.setFontSize(11)
  doc.text(`Client: ${client?.name || '—'}`, 14, y)
  y += 5
  if (client?.company) { doc.text(client.company, 14, y); y += 5 }
  if (client?.email) { doc.text(client.email, 14, y); y += 5 }
  if (client?.phone) { doc.text(client.phone, 14, y); y += 5 }
  if (client?.address) { doc.text(String(client.address).slice(0, 80), 14, y); y += 5 }
  y += 4

  doc.setDrawColor(0, 122, 77)
  doc.line(14, y, 196, y)
  y += 8

  doc.setFontSize(9)
  doc.setTextColor(100)
  doc.text('Date', 14, y)
  doc.text('Description', 36, y)
  doc.text('Debit', 118, y)
  doc.text('Credit', 145, y)
  doc.text('Balance', 172, y)
  y += 3
  doc.setDrawColor(220)
  doc.line(14, y, 196, y)
  y += 6
  doc.setTextColor(20)

  if (!lines.length) {
    doc.text('No activity on this account.', 14, y)
    y += 10
  } else {
    for (const row of lines) {
      if (y > 270) { doc.addPage(); y = 20 }
      doc.setFontSize(9)
      doc.text(String(row.date || '').slice(0, 10), 14, y)
      const desc = String(row.description || row.ref || '').slice(0, 42)
      doc.text(desc, 36, y)
      if (row.debit) doc.text(formatMoney(row.debit), 118, y)
      if (row.credit) doc.text(formatMoney(row.credit), 145, y)
      doc.text(formatMoney(row.balance), 172, y)
      y += 6
    }
  }

  y += 4
  doc.setDrawColor(0, 122, 77)
  doc.line(14, y, 196, y)
  y += 8
  doc.setFontSize(12)
  doc.setTextColor(0, 122, 77)
  doc.text(`Outstanding total: ${formatMoney(outstanding)}`, 14, y)
  y += 12
  doc.setFontSize(9)
  doc.setTextColor(100)
  if (outstanding > 0) {
    doc.text('Please settle outstanding amounts at your earliest convenience.', 14, y)
  } else {
    doc.text('Account is settled. Thank you for your payment.', 14, y)
  }
  y += 5
  doc.text(`Generated by ${co} · SA Invoice Pro`, 14, y)

  return doc.output('blob')
}

export function downloadStatementPdf(client, invoices, company, payments = []) {
  const blob = buildStatementPdfBlob(client, invoices, company, payments)
  const url = URL.createObjectURL(blob)
  const a = document.createElement('a')
  a.href = url
  a.download = `statement-${(client?.name || 'client').replace(/\s+/g, '-').slice(0, 40)}-${new Date().toISOString().slice(0, 10)}.pdf`
  a.click()
  setTimeout(() => URL.revokeObjectURL(url), 2000)
  return blob
}

export async function shareStatementPdf(client, invoices, company, { channel = 'wa', text = '', payments = [] } = {}) {
  const caption = text || buildClientStatement(client, invoices, company, payments)
  const blob = buildStatementPdfBlob(client, invoices, company, payments)
  const fileName = `statement-${(client?.name || 'client').replace(/\s+/g, '-').slice(0, 30)}.pdf`
  const file = new File([blob], fileName, { type: 'application/pdf' })

  if (typeof navigator !== 'undefined' && navigator.canShare) {
    try {
      if (navigator.canShare({ files: [file], text: caption })) {
        await navigator.share({ files: [file], title: 'Account statement', text: caption })
        return { shared: true, method: 'web-share-file-caption' }
      }
      if (navigator.canShare({ files: [file] })) {
        await navigator.share({ files: [file], title: 'Account statement', text: caption })
        return { shared: true, method: 'web-share-file' }
      }
    } catch (e) {
      if (e?.name === 'AbortError') return { shared: false, method: 'cancelled' }
    }
  }

  downloadStatementPdf(client, invoices, company, payments)
  if (channel === 'email') {
    openEmail(client?.email, `Account statement — ${company?.name || 'SA Invoice Pro'}`, caption.replace(/\*/g, ''))
  } else {
    openWhatsApp(client?.phone, caption + '\n\n_(Attach the downloaded PDF statement)_')
  }
  return { shared: false, method: 'download-plus-caption', blob, caption }
}
