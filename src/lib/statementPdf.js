import { jsPDF } from 'jspdf'
import { formatMoney } from './money'

/** Build open-invoice rows for a client */
export function openInvoicesForClient(client, invoices) {
  return (invoices || [])
    .filter((i) => String(i.clientId) === String(client?.id) && ['unpaid', 'partial', 'overdue'].includes(i.status || 'unpaid'))
    .sort((a, b) => String(a.dueDate || a.date || '').localeCompare(String(b.dueDate || b.date || '')))
}

export function statementTotals(rows) {
  return rows.reduce((s, i) => s + (Number(i.amountDue ?? i.total) || 0), 0)
}

/** Generate account statement PDF (jsPDF) and return blob */
export function buildStatementPdfBlob(client, invoices, company) {
  const rows = openInvoicesForClient(client, invoices)
  const total = statementTotals(rows)
  const doc = new jsPDF({ unit: 'mm', format: 'a4' })
  const co = company?.name || 'SA Invoice Pro'
  let y = 18

  doc.setFontSize(16)
  doc.setTextColor(0, 122, 77)
  doc.text(co, 14, y)
  y += 8
  doc.setFontSize(12)
  doc.setTextColor(30)
  doc.text('Account statement', 14, y)
  y += 7
  doc.setFontSize(10)
  doc.setTextColor(80)
  doc.text(`Date: ${new Date().toISOString().slice(0, 10)}`, 14, y)
  y += 10

  doc.setTextColor(20)
  doc.setFontSize(11)
  doc.text(`Client: ${client?.name || '—'}`, 14, y)
  y += 5
  if (client?.company) { doc.text(client.company, 14, y); y += 5 }
  if (client?.email) { doc.text(client.email, 14, y); y += 5 }
  if (client?.phone) { doc.text(client.phone, 14, y); y += 5 }
  if (client?.address) { doc.text(String(client.address).slice(0, 80), 14, y); y += 5 }
  y += 4

  doc.setDrawColor(0, 122, 77)
  doc.line(14, y, 196, y)
  y += 8

  doc.setFontSize(10)
  doc.setTextColor(100)
  doc.text('Invoice', 14, y)
  doc.text('Date', 55, y)
  doc.text('Due', 85, y)
  doc.text('Status', 115, y)
  doc.text('Balance', 160, y)
  y += 3
  doc.setDrawColor(220)
  doc.line(14, y, 196, y)
  y += 6
  doc.setTextColor(20)

  if (!rows.length) {
    doc.text('No outstanding invoices.', 14, y)
    y += 10
  } else {
    for (const inv of rows) {
      if (y > 270) { doc.addPage(); y = 20 }
      const bal = Number(inv.amountDue ?? inv.total) || 0
      doc.text(String(inv.number || '').slice(0, 18), 14, y)
      doc.text(String(inv.date || '').slice(0, 10), 55, y)
      doc.text(String(inv.dueDate || '').slice(0, 10), 85, y)
      doc.text(String(inv.status || 'unpaid'), 115, y)
      doc.text(formatMoney(bal), 160, y)
      y += 6
    }
  }

  y += 4
  doc.setDrawColor(0, 122, 77)
  doc.line(14, y, 196, y)
  y += 8
  doc.setFontSize(12)
  doc.setTextColor(0, 122, 77)
  doc.text(`Outstanding total: ${formatMoney(total)}`, 14, y)
  y += 12
  doc.setFontSize(9)
  doc.setTextColor(100)
  doc.text('Please settle outstanding amounts at your earliest convenience.', 14, y)
  y += 5
  doc.text(`Generated by ${co} · SA Invoice Pro`, 14, y)

  return doc.output('blob')
}

export function downloadStatementPdf(client, invoices, company) {
  const blob = buildStatementPdfBlob(client, invoices, company)
  const url = URL.createObjectURL(blob)
  const a = document.createElement('a')
  a.href = url
  a.download = `statement-${(client?.name || 'client').replace(/\s+/g, '-').slice(0, 40)}-${new Date().toISOString().slice(0, 10)}.pdf`
  a.click()
  setTimeout(() => URL.revokeObjectURL(url), 2000)
  return blob
}

/** Try Web Share API with PDF file; falls back to download + open WhatsApp/email */
export async function shareStatementPdf(client, invoices, company, { channel = 'wa', text = '' } = {}) {
  const blob = buildStatementPdfBlob(client, invoices, company)
  const file = new File([blob], `statement-${client?.name || 'client'}.pdf`, { type: 'application/pdf' })

  if (navigator.canShare && navigator.canShare({ files: [file] })) {
    try {
      await navigator.share({ files: [file], title: 'Account statement', text: text || 'Account statement' })
      return { shared: true, method: 'web-share' }
    } catch (e) {
      if (e?.name === 'AbortError') return { shared: false, method: 'cancelled' }
    }
  }

  // Fallback: download PDF then open channel
  downloadStatementPdf(client, invoices, company)
  return { shared: false, method: 'download-fallback', blob }
}
